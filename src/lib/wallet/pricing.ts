import connectToDatabase from '@/lib/mongodb';
import DocumentRecord from '@/models/DocumentRecord';
import mongoose from 'mongoose';
import {
  SERVICE_FEES,
  LOW_BALANCE_THRESHOLD,
  normalizeDocType,
} from './constants';

export { SERVICE_FEES, LOW_BALANCE_THRESHOLD, normalizeDocType };

/**
 * Check if the document has already been generated and saved for this user.
 * If saved, all future views, edits, and re-prints are 100% free of charge (₹0).
 */
export async function isDocumentAlreadyPaid(
  userId: string,
  docType: string,
  cardIdentifier: string
): Promise<boolean> {
  if (!userId || !cardIdentifier) return false;

  try {
    await connectToDatabase();
    const cleanId = cardIdentifier.trim().toUpperCase();
    const cleanDocType = normalizeDocType(docType);

    const query = DocumentRecord.findOne({
      userId: new mongoose.Types.ObjectId(userId),
      docType: cleanDocType as any,
      cardIdentifier: cleanId,
    });

    const existingRecord =
      typeof (query as any)?.lean === 'function' ? await query.lean() : await query;

    return Boolean(
      existingRecord &&
        ((existingRecord as any).printCount > 0 || (existingRecord as any).isPaid === true)
    );
  } catch (err) {
    console.error('[Pricing] Failed to check document payment status:', err);
    return false;
  }
}

/**
 * Calculates the required service fee for a given action.
 * Returns fee = 0 if the document was already generated by the user.
 */
export async function getRequiredServiceFee(
  userId: string,
  docType: string,
  cardIdentifier?: string,
  isManual = false
): Promise<{ fee: number; isFreeReprint: boolean; docType: string }> {
  const cleanDocType = normalizeDocType(docType);

  // If card identifier is provided, check if it's already generated
  if (cardIdentifier) {
    const isPaid = await isDocumentAlreadyPaid(userId, cleanDocType, cardIdentifier);
    if (isPaid) {
      return {
        fee: 0,
        isFreeReprint: true,
        docType: cleanDocType,
      };
    }
  }

  // If manual entry mode
  if (isManual) {
    return {
      fee: SERVICE_FEES.MANUAL,
      isFreeReprint: false,
      docType: 'MANUAL',
    };
  }

  // Standard lookup fee
  const fee = SERVICE_FEES[cleanDocType] ?? 20;

  return {
    fee,
    isFreeReprint: false,
    docType: cleanDocType,
  };
}
